"use client";
import { AlertTriangle, RotateCw } from "lucide-react";
import { useRouter } from "next/navigation";
import { useMemo, useState } from "react";
import { Button } from "@/components/ui/button";
import { useReportStream, type Snapshot } from "@/hooks/use-report-stream";
import { numbering } from "@/lib/citations";
import { isTerminal } from "@/lib/run-state";
import { ProgressPanel } from "./progress-panel";
import { ReportActions } from "./report-actions";
import { ReportArticle } from "./report-article";
import { SourcesPanel } from "./sources-panel";
import { Verification } from "./verification";

function fmtDuration(ms?: number | null) {
  if (!ms) return null;
  if (ms < 1000) return "under 1 s";
  const s = Math.round(ms / 1000);
  return s < 60 ? `${s} s` : `${Math.floor(s / 60)} min ${s % 60} s`;
}

export function ReportView({ initial, share }: { initial: Snapshot; share?: string }) {
  const router = useRouter();
  const { state, connected } = useReportStream(initial, share);
  const [active, setActive] = useState<string | null>(null);
  const r = state.report;
  const result = state.result;
  const nums = useMemo(() => (result ? numbering(result) : new Map<string, number>()), [result]);
  const running = !isTerminal(r.status);
  const failed = r.status === "failed" || r.status === "cancelled";
  const readOnly = !!share;

  const meta = [
    // Fixed locale and zone, so the server and browser render the same text.
    new Date(r.createdAt).toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" }),
    state.sources.size ? `${state.sources.size} sources` : null,
    fmtDuration(r.durationMs ?? state.doneMs),
    r.model,
  ].filter(Boolean);

  return (
    <div className="mx-auto w-full max-w-[1240px] px-4 pt-6 pb-24 sm:px-6 lg:px-10 lg:pt-10">
      <header className="mb-8 max-w-[880px]">
        <h1 className="text-[24px] leading-tight font-semibold tracking-tight text-balance sm:text-[28px]">{result?.title ?? r.query}</h1>
        {result && result.title !== r.query && <p className="mt-2 text-[14.5px] text-muted-foreground">{r.query}</p>}
        <div className="mt-4 flex flex-wrap items-center justify-between gap-3">
          <p className="tabular text-[12.5px] text-muted-foreground">{meta.join(" · ")}</p>
          <ReportActions state={state} readOnly={readOnly} />
        </div>
        {result && r.status === "completed" && (
          <div className="mt-4 border-t pt-4">
            <Verification confidence={result.confidence} evals={state.evals} detailsHref={readOnly ? undefined : `/r/${r.id}/details`} />
          </div>
        )}
      </header>

      <div className="grid grid-cols-1 gap-x-12 gap-y-10 lg:grid-cols-[minmax(0,1fr)_340px] xl:grid-cols-[minmax(0,1fr)_380px]">
        <div className="min-w-0">
          {failed && (
            <div role="alert" className="mb-6 flex gap-3 rounded-xl border border-destructive/30 bg-danger-soft p-4">
              <AlertTriangle className="mt-0.5 size-5 shrink-0 text-destructive" aria-hidden="true" />
              <div className="min-w-0 flex-1">
                <p className="text-[14px] font-medium">This research run didn&apos;t finish.</p>
                <p className="mt-1 text-[13px] text-muted-foreground">{state.error ?? r.error ?? "An unexpected error stopped the run."}</p>
              </div>
              {!readOnly && (
                <Button
                  size="sm"
                  variant="outline"
                  onClick={async () => {
                    const res = await fetch("/api/research", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ query: r.query }) });
                    const body = await res.json();
                    if (res.ok) router.push(`/r/${body.id}`);
                  }}
                >
                  <RotateCw className="size-4" /> Try again
                </Button>
              )}
            </div>
          )}
          {running && !result && <ProgressPanel state={state} connected={connected} />}
          {result && (
            <>
              {running && <p className="mb-4 text-[13px] text-muted-foreground" aria-live="polite">Checking citations…</p>}
              <ReportArticle report={result} nums={nums} sources={state.sources} active={active} onCite={(id) => setActive(id)} />
            </>
          )}
          {result && (
            <p className="mt-12 max-w-[68ch] border-t pt-4 text-[12px] leading-relaxed text-muted-foreground">
              Generated by an AI research agent from public sources. Not medical advice. Claims can be wrong even when cited — check the source before relying on it.
            </p>
          )}
        </div>
        <aside className="lg:sticky lg:top-6 lg:max-h-[calc(100dvh-3rem)] lg:self-start lg:overflow-y-auto lg:pr-1">
          <SourcesPanel sources={state.sources} nums={nums} active={active} />
        </aside>
      </div>
    </div>
  );
}
