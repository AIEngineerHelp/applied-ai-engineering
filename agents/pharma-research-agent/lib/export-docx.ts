import "server-only";
import { AlignmentType, Document, HeadingLevel, Packer, Paragraph, TextRun } from "docx";
import { blocks, numbered, numbering, referenceLine } from "./citations";
import type { SerializedReport } from "./reports";
import type { Source } from "../agent/types";

/** A Word document: title, question, answer, sections, limitations, numbered references. */
export async function reportDocx(r: SerializedReport, sources: Source[]): Promise<Buffer> {
  const report = r.report!;
  const nums = numbering(report);
  const byId = new Map(sources.map((s) => [s.id, s]));
  const para = (text: string) => new Paragraph({ children: [new TextRun({ text: numbered(text, nums), font: "Georgia", size: 22 })], spacing: { after: 160, line: 300 } });
  const body = (text: string) =>
    blocks(text).flatMap((b) => (b.kind === "p" ? [para(b.items[0])] : b.items.map((i) => new Paragraph({ bullet: { level: 0 }, children: [new TextRun({ text: numbered(i, nums), font: "Georgia", size: 22 })] }))));
  const doc = new Document({
    creator: "Pharma research agent",
    title: report.title,
    description: r.query,
    sections: [
      {
        children: [
          new Paragraph({ heading: HeadingLevel.TITLE, children: [new TextRun({ text: report.title, font: "Calibri", size: 36, bold: true })] }),
          new Paragraph({ children: [new TextRun({ text: `Question: ${r.query}`, italics: true, color: "555555", size: 20 })], spacing: { after: 80 } }),
          new Paragraph({
            children: [new TextRun({ text: `Confidence: ${report.confidence} · ${nums.size} cited sources · ${new Date(r.createdAt).toUTCString().slice(5, 16)} · ${r.model}`, color: "555555", size: 18 })],
            spacing: { after: 240 },
          }),
          ...body(report.answer),
          ...report.sections.flatMap((s) => [new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun({ text: s.heading, font: "Calibri" })], spacing: { before: 280, after: 120 } }), ...body(s.body)]),
          new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun({ text: "Limitations", font: "Calibri" })], spacing: { before: 280, after: 120 } }),
          ...report.limitations.map((l) => new Paragraph({ bullet: { level: 0 }, children: [new TextRun({ text: numbered(l, nums), font: "Georgia", size: 22 })] })),
          new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun({ text: "References", font: "Calibri" })], spacing: { before: 280, after: 120 } }),
          ...[...nums.entries()].map(([id, n]) => {
            const s = byId.get(id);
            return new Paragraph({
              children: [new TextRun({ text: `${n}. `, bold: true, size: 19 }), new TextRun({ text: s ? `${referenceLine(s)}. ${s.url}` : id, size: 19 })],
              spacing: { after: 80 },
            });
          }),
          new Paragraph({
            alignment: AlignmentType.LEFT,
            spacing: { before: 360 },
            children: [new TextRun({ text: "Generated by an AI research agent from public sources. Not medical advice; verify against the cited sources.", italics: true, color: "777777", size: 16 })],
          }),
        ],
      },
    ],
  });
  return Packer.toBuffer(doc);
}
