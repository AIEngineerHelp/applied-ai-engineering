import { Suspense } from "react";
import { AskBox } from "@/components/app/ask-box";
import { ExampleQuestions } from "@/components/app/example-questions";
import { RecentReports } from "@/components/app/recent-reports";

const STEPS = [
  ["Plans the research", "Splits your question into focused sub-questions."],
  ["Searches four sources", "PubMed, ClinicalTrials.gov, FDA labels and the web, in parallel."],
  ["Writes a cited report", "Every claim is linked to the study, trial or label it came from."],
  ["Checks itself", "Each citation is verified against what was retrieved."],
] as const;

async function Ask({ searchParams }: { searchParams: Promise<{ q?: string }> }) {
  const { q } = await searchParams;
  return <AskBox key={q ?? ""} initial={q ?? ""} autoFocus />;
}

export default function Home({ searchParams }: PageProps<"/">) {
  return (
    <div className="mx-auto w-full max-w-[760px] px-4 pt-12 pb-20 sm:px-6 lg:pt-24">
      <h1 className="text-[28px] leading-tight font-semibold tracking-tight sm:text-[32px]">Research a clinical question</h1>
      <p className="mt-2 mb-8 max-w-[60ch] text-[15px] leading-relaxed text-muted-foreground">
        Evidence reports drawn from published studies, registered trials, FDA labels and regulator announcements — with every claim cited to its source.
      </p>
      <Suspense fallback={<AskBox />}>
        <Ask searchParams={searchParams as Promise<{ q?: string }>} />
      </Suspense>
      <ol className="mt-6 grid gap-x-6 gap-y-4 border-y py-6 sm:grid-cols-2 lg:grid-cols-4">
        {STEPS.map(([title, body], i) => (
          <li key={title}>
            <div className="mb-1 flex items-center gap-2 text-[13px] font-semibold">
              <span className="tabular text-muted-foreground">{i + 1}</span>
              {title}
            </div>
            <p className="text-[12.5px] leading-snug text-muted-foreground">{body}</p>
          </li>
        ))}
      </ol>
      <div className="mt-10 space-y-10">
        <RecentReports />
        <ExampleQuestions />
      </div>
      <p className="mt-12 text-[12px] leading-relaxed text-muted-foreground">
        Reports are generated by an AI research agent from public sources. They are not medical advice and can contain errors — check the cited sources before relying on them.
      </p>
    </div>
  );
}
